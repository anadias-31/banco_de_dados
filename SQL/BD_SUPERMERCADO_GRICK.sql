/* CONSULTAR COMO SERIA AUMENTAR EM R$ 2,00 O PREÇO DOS PRODUTOS COM PREÇO ATUAL ACIMA DE R$ 5,00 */
SELECT PRO_NOME AS "NOME",
PRO_PRECO AS "PREÇO ATUAL",
        (PRO_PRECO+2) AS "PREÇO COM AUMENTO"
 FROM PRODUTO
WHERE PRO_PRECO > 5 ;

/* COMO SERIA DIMINUIR EM R$ 1,00 O PREÇO DOS PRODUTOS COM PREÇO ATUAL ABAIXO (MENOR) DE R$ 5,00 */
SELECT PRO_NOME AS "NOME",
PRO_PRECO AS "PREÇO ATUAL",
        (PRO_PRECO-1) AS "PREÇO MENOR"
 FROM PRODUTO
WHERE PRO_PRECO < 5 ;

/* CONSULTAR COMO SERIA APLICAR UM DESCONTO DE 10% PARA TODOS OS PRODUTOS */
SELECT PRO_NOME AS "NOME DO PRODUTO",
       PRO_PRECO AS "PREÇO ATUAL",
  PRO_PRECO - (PRO_PRECO * 0.1) AS "PREÇO COM DESCONTO"
FROM PRODUTO;

