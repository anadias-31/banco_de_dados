/* Fazer uma consulta para retornar a idade dos funcionarios */
SELECT FUN_NOME AS "NOME DO FUNCIONARIO",
	   DATE_FORMAT(FUN_DATA_NASCIMENTO, "%d/%m/%Y") AS "DATA DE NASCIMENTO", 
