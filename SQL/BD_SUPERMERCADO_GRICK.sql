CREATE DATABASE IF NOT EXISTS BD_SUPERMERCADO_GRICK;
USE BD_SUPERMERCADO_GRICK;

CREATE TABLE IF NOT EXISTS SUPERMERCADO(
SUP_CNPJ VARCHAR(14) PRIMARY KEY,
    SUP_RAZAO_SOCIAL VARCHAR(100) NOT NULL,
    SUP_TELEFONE VARCHAR(11) NOT NULL,
    SUP_EMAIL VARCHAR(100) NOT NULL,
    SUP_ENDERECO_LOGRADOURO VARCHAR(100) NOT NULL,
    SUP_ENDERECO_NUMERO VARCHAR(5),
    SUP_ENDERECO_CIDADE VARCHAR(100) NOT NULL,
    SUP_ENDERECO_ESTADO VARCHAR(2) NOT NULL
);

CREATE TABLE IF NOT EXISTS PRODUTO(
PRO_ID INT AUTO_INCREMENT PRIMARY KEY,
    PRO_CODIGO_BARRAS VARCHAR(50) NOT NULL,
    PRO_NOME VARCHAR(100) NOT NULL,
    PRO_PESO DOUBLE,
    PRO_QUANTIDADE INT NOT NULL,
    PRO_PRECO DOUBLE NOT NULL,
    PRO_DATA_VALIDADE DATE
);

CREATE TABLE IF NOT EXISTS CONSUMIDOR(
CON_CPF VARCHAR(11) PRIMARY KEY,
    CON_NOME VARCHAR(100) NOT NULL,
    CON_TELEFONE VARCHAR(11) NOT NULL,
    CON_EMAIL VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS CONSUMIDOR_EXCLUIDO(
CON_CPF VARCHAR(11) PRIMARY KEY,
    CON_NOME VARCHAR(100) NOT NULL,
    CON_TELEFONE VARCHAR(11) NOT NULL,
    CON_EMAIL VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS FUNCIONARIO(
FUN_CPF VARCHAR(11) PRIMARY KEY,
    FUN_NOME VARCHAR(100) NOT NULL,
    FUN_DATA_NASCIMENTO DATE NOT NULL,
    FUN_TELEFONE VARCHAR(11) NOT NULL,
    FUN_EMAIL VARCHAR(100) NOT NULL,
    FUN_CARTEIRA_TRABALHO VARCHAR(100),
    FUN_BANCO_AGENCIA VARCHAR(5),
    FUN_BANCO_CONTA VARCHAR(10),
    FUN_DATA_ADMISSAO DATE NOT NULL,
    FUN_JORNADA_TRABALHO VARCHAR(100) NOT NULL,
    FK_SUP_CNPJ VARCHAR(14) NOT NULL,
    FOREIGN KEY (FK_SUP_CNPJ) REFERENCES SUPERMERCADO(SUP_CNPJ)
);

CREATE TABLE IF NOT EXISTS SUPERMERCADO_PRODUTO(
SPR_ID INT AUTO_INCREMENT PRIMARY KEY,
    FK_SUP_CNPJ VARCHAR(14),
    FK_PRO_ID INT,
    FOREIGN KEY (FK_SUP_CNPJ) REFERENCES SUPERMERCADO(SUP_CNPJ),
    FOREIGN KEY (FK_PRO_ID) REFERENCES PRODUTO(PRO_ID)
);

CREATE TABLE IF NOT EXISTS PRODUTO_CONSUMIDOR(
PCO_ID INT AUTO_INCREMENT PRIMARY KEY,
    FK_CON_CPF VARCHAR(14),
    FK_PRO_ID INT,
    FOREIGN KEY (FK_CON_CPF) REFERENCES CONSUMIDOR(CON_CPF),
    FOREIGN KEY (FK_PRO_ID) REFERENCES PRODUTO(PRO_ID)
);

