/* Agrupar produtos com a mesma quantidade de estoque */
SELECT PRO_QUANTIDADE AS "QUANTIDADE DE ESTOQUE",
	   COUNT(*) AS "REPETIÇOES"
FROM   PRODUTO
GROUP BY PRO_QUANTIDADE;

/* Juntar os consumidores com os consumidores excluidos */
