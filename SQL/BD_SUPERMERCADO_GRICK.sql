/* Consultar como seria aumentar em R$2,00 o preço dos produtos compreço atual acima de R$5,00 */
SELECT 	 PRO_NOME AS "NOME",
		 PRO_PRECO AS "PREÇO ATUAL",
         (PRO_PRECO + 2) AS "PREÇO COM AUMENTO"
FROM	 PRODUTO
WHERE    PRO_PRECO > 5;

/* Consultar como seria diminuir em R$1,00 o preço dos produtos com preço atual abaixo(menor) de R$5,00 */
SELECT 	 PRO_NOME AS "NOME",
		 PRO_PRECO AS "PREÇO ATUAL",
         (PRO_PRECO - 1) AS "PREÇO COM DESCONTO "
FROM	 PRODUTO
WHERE    PRO_PRECO < 5;

/* Como seria aplicar um desconto de 10% para todos os produtos */
SELECT 	 PRO_NOME AS "NOME",
		 PRO_PRECO AS "PREÇO ATUAL",
         PRO_PRECO-(PRO_PRECO * 0.1) AS "PREÇO COM DESCONTO "
FROM	 PRODUTO;

