/* VIEW:
-São peseudo-tabelas que gravam sql grandes para serem executas em diversas partes do código, sem precisar reeescrever o SELECT */
-- Criar uma view para retornar os funcionários e seus supermercados
CREATE VIEW VW_FUNCIONARIOS_SUPERMERCADOS AS 
SELECT  F.FUN_CPF AS "CPF",
		F.FUN_NOME AS "NOME", 
		F.FUN_DATA_NASCIMENTO AS "DATA DE NASCIMENTO",
		F.FUN_TELEFONE  AS "TELEFONE",
		F.FUN_EMAIL AS "E-MAIL",
		F.FUN_CARTEIRA_TRABALHO AS "CARTEIRA DE TRABALHO", 
		F.FUN_BANCO_AGENCIA  AS "AGÊNCIA DO BANCO",
		F.FUN_BANCO_CONTA  AS "CONTA DO BANCO",
		F.FUN_DATA_ADMISSAO  AS "DATA DE ADIMISSÃO",
		F.FUN_JORNADA_TRABALHO  AS "JORNADA DE TRABALHO",
		S.SUP_RAZAO_SOCIAL AS "SUPERMERCADO QUE TRABALHO"
FROM    FUNCIONARIO F
JOIN    SUPERMERCADO S ON  (S.SUP_CNPJ = F.FK_SUP_CNPJ);

SELECT * FROM VW_FUNCIONARIOS_SUPERMERCADOS;

SELECT * FROM VW_FUNCIONARIOS_SUPERMERCADOS
WHERE    UPPER(NOME) LIKE '%RAFAL%' ;


